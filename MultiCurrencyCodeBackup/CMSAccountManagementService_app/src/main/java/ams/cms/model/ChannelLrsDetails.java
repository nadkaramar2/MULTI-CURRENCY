package ams.cms.model;

public class ChannelLrsDetails {
	
	private String channel;
	private String lrsLimit;
	private String lrsConsumed;
	private String tcsApplied;
	private String totalLoaded;
	public String getChannel() {
		return channel;
	}
	public void setChannel(String channel) {
		this.channel = channel;
	}
	public String getLrsLimit() {
		return lrsLimit;
	}
	public void setLrsLimit(String lrsLimit) {
		this.lrsLimit = lrsLimit;
	}
	public String getLrsConsumed() {
		return lrsConsumed;
	}
	public void setLrsConsumed(String lrsConsumed) {
		this.lrsConsumed = lrsConsumed;
	}
	public String getTcsApplied() {
		return tcsApplied;
	}
	public void setTcsApplied(String tcsApplied) {
		this.tcsApplied = tcsApplied;
	}
	public String getTotalLoaded() {
		return totalLoaded;
	}
	public void setTotalLoaded(String totalLoaded) {
		this.totalLoaded = totalLoaded;
	}
	
	

}
